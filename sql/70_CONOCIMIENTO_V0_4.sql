BEGIN
    EXECUTE IMMEDIATE q'[
        CREATE TABLE GT_CONOCIMIENTO (
            ID_CONOCIMIENTO       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            TIPO                  VARCHAR2(40 CHAR) NOT NULL,
            TITULO                VARCHAR2(250 CHAR) NOT NULL,
            RESUMEN               VARCHAR2(1000 CHAR),
            CONTENIDO             CLOB,
            ETIQUETAS             VARCHAR2(1000 CHAR),
            ESTADO                VARCHAR2(30 CHAR) DEFAULT 'BORRADOR' NOT NULL,
            ID_UNIDAD_DUENA       NUMBER NOT NULL,
            ID_PROPIETARIO        NUMBER NOT NULL,
            ID_REVISOR            NUMBER,
            CLASIFICACION         VARCHAR2(20 CHAR) DEFAULT 'INTERNO' NOT NULL,
            VERSION_ACTUAL        NUMBER DEFAULT 1 NOT NULL,
            FECHA_VIGENCIA        DATE,
            FECHA_PROX_REVISION   DATE,
            MOTIVO_ULTIMO_CAMBIO  VARCHAR2(1000 CHAR),
            FECHA_CREACION        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            CREADO_POR            NUMBER NOT NULL,
            FECHA_MODIFICACION    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            MODIFICADO_POR        NUMBER NOT NULL,
            ACTIVO                CHAR(1 CHAR) DEFAULT 'S' NOT NULL,
            CONSTRAINT PK_GT_CONOCIMIENTO PRIMARY KEY (ID_CONOCIMIENTO),
            CONSTRAINT FK_GT_CON_UNIDAD FOREIGN KEY (ID_UNIDAD_DUENA)
                REFERENCES GT_ORG_UNIDAD (ID_UNIDAD),
            CONSTRAINT FK_GT_CON_PROP FOREIGN KEY (ID_PROPIETARIO)
                REFERENCES GT_USUARIO (ID_USUARIO),
            CONSTRAINT FK_GT_CON_REVISOR FOREIGN KEY (ID_REVISOR)
                REFERENCES GT_USUARIO (ID_USUARIO),
            CONSTRAINT FK_GT_CON_CREADO FOREIGN KEY (CREADO_POR)
                REFERENCES GT_USUARIO (ID_USUARIO),
            CONSTRAINT FK_GT_CON_MODIF FOREIGN KEY (MODIFICADO_POR)
                REFERENCES GT_USUARIO (ID_USUARIO),
            CONSTRAINT CK_GT_CON_TIPO CHECK (
                TIPO IN (
                    'PROCEDIMIENTO','INSTRUCTIVO','MANUAL','CHECKLIST_CONTROL',
                    'REGLA_NEGOCIO','DECISION_OPERACIONAL','INCIDENTE_SOLUCION',
                    'SCRIPT_HERRAMIENTA','DOCUMENTO_PROYECTO','PLANTILLA','EVIDENCIA_REFERENCIA'
                )
            ),
            CONSTRAINT CK_GT_CON_ESTADO CHECK (
                ESTADO IN ('BORRADOR','EN_REVISION','PUBLICADO','REQUIERE_ACTUALIZACION','OBSOLETO')
            ),
            CONSTRAINT CK_GT_CON_CLASIF CHECK (
                CLASIFICACION IN ('INTERNO','RESTRINGIDO','CONFIDENCIAL')
            ),
            CONSTRAINT CK_GT_CON_ACTIVO CHECK (ACTIVO IN ('S','N')),
            CONSTRAINT CK_GT_CON_VERSION CHECK (VERSION_ACTUAL >= 1)
        )
    ]';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
